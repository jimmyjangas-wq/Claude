"""Write the TUFLOW model: folder structure, control files and GIS layers.

Generated structure (TUFLOW conventions):

    <output_dir>/
      runs/                 .tcf, .tef, run log folder
      model/                .tgc, .tbc, materials.csv
      model/gis/            2d_code, 2d_loc, 2d_mat (PRE/POST), 2d_rf, 2d_bc, 2d_po, QA layers
      model/grid/           (DEM to be supplied by the modeller)
      bc_dbase/             bc_dbase.csv + rainfall/*.csv
      check/  results/      TUFLOW outputs
      <model_id>_run_all.bat
"""

from __future__ import annotations

from pathlib import Path

import geopandas as gpd
import pandas as pd
from shapely.geometry import LineString, Point, box

from .catchments import scenario_summary
from .config import BuildConfig
from .rainfall import aep_event_name, duration_event_name

GENERATED_NOTE = ("Generated by NZ TUFLOW Flood Model Builder - review all files, "
                  "the DEM reference and boundary locations before running.")


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _folders(root: Path) -> dict[str, Path]:
    f = {
        "root": root,
        "runs": root / "runs",
        "runs_log": root / "runs" / "log",
        "model": root / "model",
        "gis": root / "model" / "gis",
        "grid": root / "model" / "grid",
        "bc": root / "bc_dbase",
        "rainfall": root / "bc_dbase" / "rainfall",
        "check": root / "check",
        "results": root / "results",
        "report": root / "report",
    }
    for p in f.values():
        p.mkdir(parents=True, exist_ok=True)
    return f


def _write_gis(gdf: gpd.GeoDataFrame, folder: Path, name: str, cfg: BuildConfig) -> str:
    """Write a GIS layer in the configured format; return the file name."""
    gdf = gdf.set_crs(epsg=cfg.epsg, allow_override=True)
    if cfg.gis_format == "shp":
        fn = f"{name}.shp"
        gdf.to_file(folder / fn)
    else:
        fn = f"{name}.gpkg"
        gdf.to_file(folder / fn, layer=name, driver="GPKG")
    return fn


def _domain(pre: gpd.GeoDataFrame, post: gpd.GeoDataFrame, cfg: BuildConfig):
    """Active-area polygon = buffered union of both scenarios' catchments."""
    union = pd.concat([pre.geometry, post.geometry], ignore_index=True).union_all()
    return union.buffer(cfg.grid_buffer)


# ---------------------------------------------------------------------------
# GIS layers
# ---------------------------------------------------------------------------

def write_gis_layers(pre: gpd.GeoDataFrame, post: gpd.GeoDataFrame,
                     cfg: BuildConfig, gis_dir: Path) -> dict[str, str]:
    files: dict[str, str] = {}
    mid = cfg.model_id
    domain = _domain(pre, post, cfg)
    minx, miny, maxx, maxy = domain.bounds

    # 2d_mat — material polygons per scenario (attribute 1 must be Material)
    for label, gdf in (("PRE", pre), ("POST", post)):
        mat = gdf[["material", "geometry"]].rename(columns={"material": "Material"})
        files[f"mat_{label}"] = _write_gis(mat, gis_dir, f"2d_mat_{mid}_{label}_001", cfg)
        # QA copy with full attribution for checking the auto-assignment
        qa = gdf.drop(columns=["scenario"], errors="ignore")
        files[f"qa_{label}"] = _write_gis(qa, gis_dir, f"0_qa_catchments_{label}", cfg)

    # 2d_code — active area (Code = 1)
    code = gpd.GeoDataFrame({"Code": [1]}, geometry=[domain], crs=f"EPSG:{cfg.epsg}")
    files["code"] = _write_gis(code, gis_dir, f"2d_code_{mid}_001", cfg)

    # 2d_loc — grid origin/orientation line along the SW edge of the domain
    loc = gpd.GeoDataFrame({"Comment": ["origin at first vertex, x-axis along line"]},
                           geometry=[LineString([(minx, miny), (maxx, miny)])],
                           crs=f"EPSG:{cfg.epsg}")
    files["loc"] = _write_gis(loc, gis_dir, f"2d_loc_{mid}_001", cfg)

    # 2d_rf — rainfall polygon over the active area (rain-on-grid)
    rf = gpd.GeoDataFrame({"Name": ["RF01"], "f1": [1.0], "f2": [1.0]},
                          geometry=[domain], crs=f"EPSG:{cfg.epsg}")
    files["rf"] = _write_gis(rf, gis_dir, f"2d_rf_{mid}_001", cfg)

    # 2d_bc — placeholder HQ (normal-depth) outlet along the downstream edge.
    # PLACE THIS LINE AT THE TRUE DOWNSTREAM BOUNDARY BEFORE RUNNING.
    bc_line = LineString([(minx + (maxx - minx) * 0.25, miny),
                          (minx + (maxx - minx) * 0.75, miny)])
    bc = gpd.GeoDataFrame(
        {"Type": ["HQ"], "Flags": [""], "Name": ["DS_OUT"], "f": [0.0],
         "d": [0.0], "td": [0.0], "a": [0.0], "b": [0.01]},
        geometry=[bc_line], crs=f"EPSG:{cfg.epsg}")
    files["bc"] = _write_gis(bc, gis_dir, f"2d_bc_{mid}_001", cfg)

    # 2d_po — reporting: water-level point at each catchment centroid (post
    # names preferred) and a template flow line just inside the outlet.
    pts, labels = [], []
    seen = set()
    for _, row in pd.concat([post, pre], ignore_index=True).iterrows():
        lbl = f"H_{_safe_label(row['catch_name'])}"
        if lbl in seen:
            continue
        seen.add(lbl)
        pts.append(row.geometry.representative_point())
        labels.append(lbl)
    po_pts = gpd.GeoDataFrame({"Type": ["H_"] * len(pts), "Label": labels},
                              geometry=pts, crs=f"EPSG:{cfg.epsg}")
    files["po_points"] = _write_gis(po_pts, gis_dir, f"2d_po_{mid}_P_001", cfg)

    q_line = LineString([(minx + (maxx - minx) * 0.25, miny + cfg.cell_size * 3),
                         (minx + (maxx - minx) * 0.75, miny + cfg.cell_size * 3)])
    po_ln = gpd.GeoDataFrame({"Type": ["Q_"], "Label": ["Q_OUTLET"]},
                             geometry=[q_line], crs=f"EPSG:{cfg.epsg}")
    files["po_lines"] = _write_gis(po_ln, gis_dir, f"2d_po_{mid}_L_001", cfg)

    files["_grid"] = {
        "nx": int((maxx - minx) // cfg.cell_size + 1),
        "ny": int((maxy - miny) // cfg.cell_size + 1),
        "size_x": round(maxx - minx, 1),
        "size_y": round(maxy - miny, 1),
    }
    return files


def _safe_label(name: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in str(name)).strip("_")[:40]


